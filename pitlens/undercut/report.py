"""`pitlens undercut`: pit stops, pit loss and undercut battles for one race."""

import argparse
import platform
import subprocess

from pitlens.htmlreport import table, text, write_report
from pitlens.pitwall.data import load_race
from pitlens.session import OUTPUT_DIR
from pitlens.undercut.analysis import pair_gap, pit_battles, pit_loss, pit_stops
from pitlens.undercut.charts import battle_chart, pit_loss_chart

MAX_BATTLE_CHARTS = 8


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--year", type=int, default=2025)
    parser.add_argument("--event", default="Hungary", help="Event name, location or round number")
    parser.add_argument("--max-gap", type=float, default=3.5, help="Cars within this many seconds count as a battle")
    parser.add_argument("--open", action="store_true", help="Open the report in the browser when done (macOS)")


def run(args: argparse.Namespace) -> None:
    event = int(args.event) if str(args.event).isdigit() else args.event
    print(f"Loading {args.year} {args.event} race...")
    race = load_race(args.year, event)
    stops = pit_stops(race.laps)
    loss = pit_loss(stops)
    battles = pit_battles(race.laps, stops, max_gap=args.max_gap)

    print(f"\n{race.name}: {len(stops)} stops, typical green-flag pit loss "
          + (f"{loss:.1f} s" if loss is not None else "unknown"))
    print(stops.to_string(index=False))
    print("\nUndercut and overcut battles:" if not battles.empty else "\nNo close pit battles found.")
    if not battles.empty:
        print(battles.to_string(index=False))

    out_dir = OUTPUT_DIR / "undercut"
    out_dir.mkdir(parents=True, exist_ok=True)
    slug = race.name.lower().replace(" ", "_")
    report = out_dir / f"{slug}.html"

    battle_blocks = []
    for battle in battles.head(MAX_BATTLE_CHARTS).itertuples():
        gap = pair_gap(race.laps, battle.FirstStop, battle.Rival)
        battle_blocks.append(
            text(f"Lap {battle.Lap}: {battle.FirstStop} pits first, {battle.Rival} answers on lap "
                 f"{battle.RivalStopLap}. {battle.Verdict}; {battle.FirstStop} gained {battle.Gained:+.2f} s.")
        )
        battle_blocks.append(battle_chart(gap, battle, race.total_laps))

    write_report(
        report,
        f"{race.name}: pit stops and undercuts",
        "Generated by PitLens from public F1 timing data via FastF1 (unofficial).",
        [
            ("Pit loss", [
                text("Time each stop cost compared with the car's normal lap times around it. "
                     "The typical figure uses green-flag stops only."),
                pit_loss_chart(stops, loss, race.total_laps),
            ]),
            ("Undercuts and overcuts", [
                text(f"Pairs of cars within {args.max_gap:.1f} s when the first of them pitted, where the other "
                     "pitted within six laps. Gap before is at the end of the lap before the first stop; gap "
                     "after is once both have been through the pits. Positive gaps mean the first stopper is behind."),
                table(battles),
                *battle_blocks,
            ]),
            ("Every stop", [table(stops)]),
        ],
    )
    stops.to_csv(out_dir / f"{slug}_stops.csv", index=False)
    battles.to_csv(out_dir / f"{slug}_battles.csv", index=False)
    print(f"\nSaved {report}")

    if args.open and platform.system() == "Darwin":
        subprocess.run(["open", str(report)], check=False)

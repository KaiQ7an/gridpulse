"""`pitlens onboard`: compare two drivers' fastest laps in one session."""

import argparse
import platform
import subprocess

import pandas as pd

from pitlens.onboard.charts import telemetry_figure, track_map
from pitlens.onboard.compare import align, corner_speeds, minisectors
from pitlens.onboard.data import SESSION_NAMES, OnboardData, compare, load_session_with_telemetry, session_drivers, teammate_of
from pitlens.htmlreport import table, text, write_report
from pitlens.pitwall.timing import format_lap_time
from pitlens.session import OUTPUT_DIR


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--year", type=int, default=2025)
    parser.add_argument("--event", default="Hungary", help="Event name, location or round number")
    parser.add_argument("--session", default="Q", choices=list(SESSION_NAMES), help="Session (default qualifying)")
    parser.add_argument(
        "--drivers", nargs="+", metavar="DRV",
        help="One or two driver codes, e.g. NOR PIA. Default: the fastest driver and their teammate",
    )
    parser.add_argument("--open", action="store_true", help="Open the report in the browser when done (macOS)")


def summary_table(data: OnboardData) -> pd.DataFrame:
    rows = []
    for lap in (data.ref, data.other):
        rows.append(
            {
                "Driver": lap.driver,
                "Lap": format_lap_time(lap.lap_time),
                "S1": format_lap_time(lap.sectors[0]),
                "S2": format_lap_time(lap.sectors[1]),
                "S3": format_lap_time(lap.sectors[2]),
                "Top speed": f"{lap.telemetry['Speed'].max():.0f} km/h",
                "Tyre": f"{lap.compound.title()}, {lap.tyre_life:.0f} laps old",
            }
        )
    return pd.DataFrame(rows)


def run(args: argparse.Namespace) -> None:
    event = int(args.event) if str(args.event).isdigit() else args.event
    print(f"Loading {args.year} {args.event} {SESSION_NAMES[args.session]} with telemetry...")
    session = load_session_with_telemetry(args.year, event, args.session)

    drivers = session_drivers(session)
    picked = [d.upper() for d in (args.drivers or [])]
    ref = picked[0] if picked else drivers["Driver"].iloc[0]
    other = picked[1] if len(picked) > 1 else teammate_of(drivers, ref)
    if other is None:
        raise SystemExit(f"Couldn't find a teammate for {ref}; pass two drivers with --drivers")

    try:
        data = compare(session, ref, other)
    except ValueError as exc:
        raise SystemExit(f"{exc}. Pick other drivers with --drivers.") from None
    aligned = align(data.ref.telemetry, data.other.telemetry)
    sectors = minisectors(aligned)
    corners = corner_speeds(data.ref.telemetry, data.other.telemetry, data.corners)

    title = f"{data.name} {data.session_name}: {ref} vs {other}"
    summary = summary_table(data)
    gap = (data.other.lap_time - data.ref.lap_time).total_seconds()
    print(f"\n{title}\n")
    print(summary.to_string(index=False))
    print(f"\n{other} is {gap:+.3f} s vs {ref}. Mini-sectors won: "
          f"{ref} {int((sectors['Faster'] == 'ref').sum())}, {other} {int((sectors['Faster'] == 'other').sum())}")
    if not corners.empty:
        best = corners.sort_values("Gain")
        print(f"Biggest gains for {ref}: " + ", ".join(f"T{r.Corner} {r.Gain:+.3f}s" for r in best.tail(3)[::-1].itertuples()))
        print(f"Biggest gains for {other}: " + ", ".join(f"T{r.Corner} {-r.Gain:+.3f}s" for r in best.head(3).itertuples()))

    slug = f"{data.name.lower().replace(' ', '_')}_{args.session.lower()}_{ref}_vs_{other}"
    out_dir = OUTPUT_DIR / "onboard"
    out_dir.mkdir(parents=True, exist_ok=True)
    report = out_dir / f"{slug}.html"
    corner_table = corners.rename(columns={"RefMinSpeed": f"{ref} min km/h", "OtherMinSpeed": f"{other} min km/h",
                                           "SpeedDiff": "Speed diff", "Gain": f"{ref} gain (s)"})
    write_report(
        report,
        title,
        "Fastest laps compared. Generated by PitLens from public F1 timing data via FastF1 (unofficial).",
        [
            (None, [table(summary), telemetry_figure(data, aligned)]),
            ("Who was faster where", [track_map(data, sectors)]),
            (
                "Corner by corner",
                [text(f"Minimum speed through each corner and time gained by {ref} (positive) or lost (negative)."),
                 table(corner_table)],
            ),
        ],
    )
    corners.to_csv(out_dir / f"{slug}_corners.csv", index=False)
    print(f"\nSaved {report}")

    if args.open and platform.system() == "Darwin":
        subprocess.run(["open", str(report)], check=False)
